public class OOPSBanner {
    public static void main(String[] args) {

        String[] oops = {
            "OOOO   OOOO   PPPP    SSSSS ",
            "O   O  O   O  P   P  S      ",
            "O   O  O   O  PPPP    SSSS   ",
            "O   O  O   O  P           S  ",
            "OOOO   OOOO   P      SSSSS   "
        };

        for (String line : oops) {
            System.out.println(line);
        }
    }
}